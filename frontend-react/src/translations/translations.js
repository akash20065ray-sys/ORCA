/**
 * Universal translation helper.
 * Looks up the key in the target language. Falls back to English, then defaultText.
 */
export function translate(key, lang = 'en', defaultText = '') {
  const effectiveLang = TRANSLATIONS[lang] ? lang : 'en';
  if (TRANSLATIONS[effectiveLang] && TRANSLATIONS[effectiveLang][key]) {
    return TRANSLATIONS[effectiveLang][key];
  }
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
    return TRANSLATIONS.en[key];
  }
  return defaultText || key;
}
