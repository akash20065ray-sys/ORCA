function changeGlobalAppLanguage(langCode) {
  if (!langCode) return;
  localStorage.setItem('orca_app_language', langCode);

  const t = ORCA_TRANSLATIONS[langCode] || ORCA_TRANSLATIONS['en'];
  const en = ORCA_TRANSLATIONS['en'];
  const get = (key) => t[key] || en[key] || '';

  // 1. Header Brand & Subtitle
  const brandTitleEl = document.querySelector('.brand-title');
  if (brandTitleEl) brandTitleEl.textContent = get('brandTitle');
  const brandSubEl = document.querySelector('.brand-subtitle');
  if (brandSubEl) brandSubEl.textContent = get('brandSubtitle');

  // 2. GPS Text
  const gpsTextEl = document.querySelector('#headerGpsPill .gps-text');
  if (gpsTextEl) gpsTextEl.textContent = get('gpsActive');

  // 3. Left Navigation Links
  const navLinks = document.querySelectorAll('.sidebar-nav .nav-link');
  navLinks.forEach((link) => {
    const view = link.getAttribute('data-view');
    const label = link.querySelector('.nav-label');
    if (!label) return;
    if (view === 'home') label.textContent = get('navHome');
    else if (view === 'chat') label.textContent = get('navChat');
    else if (view === 'routes') label.textContent = get('navRoutes');
    else if (view === 'safety') label.textContent = get('navSafety');
  });

  // 4. Sidebar Footer
  const statusTitle = document.querySelector('.status-title');
  if (statusTitle) statusTitle.textContent = get('statusOnline');
  const statusSub = document.querySelector('.status-sub');
  if (statusSub) statusSub.textContent = get('statusSub');
  const syncTitle = document.querySelector('.sync-title');
  if (syncTitle) syncTitle.textContent = get('dataUpdated');
  const syncBtn = document.querySelector('.sync-refresh-btn');
  if (syncBtn) syncBtn.textContent = get('syncBtn');

  // 5. Chat Input Placeholder
  const chatInput = document.getElementById('chatInput');
  if (chatInput) chatInput.setAttribute('placeholder', get('chatPlaceholder'));

  // 6. Quick Action Chips
  const chipWaves = document.querySelector('.chip[data-prompt*="waves"], .quick-chip[data-topic="waves"]');
  if (chipWaves) chipWaves.textContent = '🌊 ' + get('chipWaves');
  const chipWind = document.querySelector('.chip[data-prompt*="wind"], .quick-chip[data-topic="wind"]');
  if (chipWind) chipWind.textContent = '💨 ' + get('chipWind');
  const chipCurrents = document.querySelector('.chip[data-prompt*="current"], .quick-chip[data-topic="currents"]');
  if (chipCurrents) chipCurrents.textContent = '🌀 ' + get('chipCurrents');
  const chipSST = document.querySelector('.chip[data-prompt*="sst"], .quick-chip[data-topic="sst"]');
  if (chipSST) chipSST.textContent = '🌡️ ' + get('chipSST');
  const chipPFZ = document.querySelector('.chip[data-prompt*="pfz"], .quick-chip[data-topic="pfz"]');
  if (chipPFZ) chipPFZ.textContent = '🐟 ' + get('chipPFZ');

  // Sync select element value
  const selectEl = document.getElementById('globalAppLanguageSelect');
  if (selectEl && selectEl.value !== langCode) {
    selectEl.value = langCode;
  }
}

